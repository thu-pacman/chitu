# This file is used to generate a temporary requirements.txt file from
# dynamic dependencies to be resolved in setup.py. This is useful for
# build a Docker stage that only triggers rebuilds by changes of this
# file.
#
# Usage `./gen_tmp_requirements_txt.py "extra1,extra2" [--kind all|pypi|local]`,
# where `extra1` and `extra2` are the extra dependency sets you want to
# include, and `--kind` selects which requirements to print:
# - `all` (default): every requirement, as before;
# - `pypi`: only requirements fetched from an index, i.e. without `file://`;
# - `local`: only requirements built from the local source tree, i.e. with
#   `file://`.
#
# Please note that the requirements.txt generated by this script does not
# include build time dependencies. Please install requirements-build.txt
# before running this script, or some dependencies may fail to install.

import sys

from get_requires import install_requires, extras_require


def print_usage():
    print(
        f"Usage: {sys.argv[0]} [extra1,extra2,...] [--kind all|pypi|local]",
        file=sys.stderr,
    )


args = sys.argv[1:]
kind = "all"
if "--kind" in args:
    index = args.index("--kind")
    if index + 1 >= len(args):
        print_usage()
        sys.exit(1)
    kind = args[index + 1]
    del args[index : index + 2]
if kind not in ("all", "pypi", "local"):
    print(f"Unknown --kind '{kind}'. Available: all, pypi, local", file=sys.stderr)
    sys.exit(1)

if len(args) > 1:
    print_usage()
    sys.exit(1)
extras = args[0].split(",") if args and args[0] else []

requires = list(install_requires)
for extra in extras:
    if extra not in extras_require:
        raise ValueError(
            f"Unknown extra '{extra}'. Available extras: {', '.join(extras_require.keys())}"
        )
    requires += extras_require[extra]

for require in requires:
    is_local = "file://" in require
    if kind == "pypi" and is_local:
        continue
    if kind == "local" and not is_local:
        continue
    print(require)
